// One self-contained bundle per entry point. The heartbeat daemon in particular
// is started as its own process, so it must not depend on shared chunks.
import fs from 'node:fs'
import commonjs from '@rollup/plugin-commonjs'
import { nodeResolve } from '@rollup/plugin-node-resolve'
import typescript from '@rollup/plugin-typescript'
import license from 'rollup-plugin-license'

const entries = ['main', 'post', 'release', 'heartbeat']

// Bundling drops the licence files of the packages it inlines, and their
// licences (MIT) ask for the notices to travel with every copy. Each build
// adds the packages it bundled, and the file is rewritten with all of them,
// sorted, so the result does not depend on the build order.
const LICENSES_FILE = 'dist/licenses.txt'
const bundled = new Map()

function repositoryUrl(repository) {
  const url = typeof repository === 'string' ? repository : repository?.url
  if (!url) return null
  // package.json allows the GitHub shorthand "owner/repo".
  if (/^[\w.-]+\/[\w.-]+$/.test(url)) return `https://github.com/${url}`
  return url.replace(/^git\+/, '').replace(/\.git$/, '')
}

function writeLicenses(dependencies) {
  for (const dep of dependencies) bundled.set(`${dep.name}@${dep.version}`, dep)
  const deps = [...bundled.values()].sort((a, b) =>
    a.name === b.name ? 0 : a.name < b.name ? -1 : 1
  )
  const text = (s) => s.replace(/\r\n/g, '\n').trim()
  const sections = deps.map((dep) => {
    const lines = [`${dep.name} ${dep.version}`, `License: ${dep.license}`]
    const repo = repositoryUrl(dep.repository)
    if (repo) lines.push(`Repository: ${repo}`)
    lines.push(
      '',
      dep.licenseText
        ? text(dep.licenseText)
        : '(no licence file in the package)'
    )
    if (dep.noticeText) lines.push('', text(dep.noticeText))
    return lines.join('\n')
  })
  const header = [
    'Third-party packages bundled into dist/*.js, with their licences.',
    'Generated by `npm run package` (rollup.config.js). Do not edit.',
    'The action itself is under the MIT License: see LICENSE at the repository root.'
  ].join('\n')
  const rule = '\n\n' + '-'.repeat(80) + '\n\n'
  fs.mkdirSync('dist', { recursive: true })
  fs.writeFileSync(LICENSES_FILE, [header, ...sections].join(rule) + '\n')
}

export default entries.map((name) => ({
  input: `src/entry/${name}.ts`,
  output: {
    file: `dist/${name}.js`,
    format: 'es',
    sourcemap: false,
    inlineDynamicImports: true
  },
  plugins: [
    typescript({ tsconfig: './tsconfig.build.json' }),
    nodeResolve({ preferBuiltins: true }),
    commonjs(),
    license({
      thirdParty: {
        includePrivate: false,
        // A bundled package under a licence outside this list fails the build.
        allow: {
          test: '(MIT OR ISC OR BSD-2-Clause OR BSD-3-Clause OR Apache-2.0 OR 0BSD)',
          failOnUnlicensed: true,
          failOnViolation: true
        },
        output: writeLicenses
      }
    })
  ],
  onwarn(warning, warn) {
    // @actions/core and its dependencies have internal circular imports and
    // TypeScript-emitted top-level `this`; both are harmless.
    if (
      warning.code === 'CIRCULAR_DEPENDENCY' &&
      (warning.ids ?? []).every((id) => id.includes('node_modules'))
    ) {
      return
    }
    if (
      warning.code === 'THIS_IS_UNDEFINED' &&
      (warning.id ?? '').includes('node_modules')
    ) {
      return
    }
    warn(warning)
  }
}))
